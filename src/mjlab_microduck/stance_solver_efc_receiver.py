"""Independent complete-file positive EFC transition receiver; never qualification.

The caller supplies externally obtained inventory and retired-unit evidence.
Whole bytes are authenticated before records/packets are decoded. Matching
invented anchors is not independent capture-origin or driver-code evidence.
"""
from hashlib import sha256
from pathlib import Path
import re

from mjlab_microduck import stance_solver_replay_receiver as old
from mjlab_microduck import stance_solver_efc_probe as probe
from mjlab_microduck import stance_solver_cost_binary as binary
from mjlab_microduck import stance_solver_cost_dispatch as dispatch
from mjlab_microduck import stance_solver_cost_executable as executable
from mjlab_microduck import stance_solver_cost_stages as stages
from mjlab_microduck import stance_solver_scratch as scratch
from mjlab_microduck import stance_solver_efc_transition as transition

PROTOCOL = "microduck-efc-transition-receiver-oct9-v1"
need = old.need


def _json(raw, label):
    value = old._json(raw, label)
    need(old._canonical(value) == raw, "canonical JSON record " + label)
    return value


def _artifact(raw, inventory, row, root):
    need(type(row) is dict and set(row) == {"path", "bytes", "sha256", "identity"}, "whole generated file anchor")
    p = Path(row["path"])
    need(p.is_absolute() and str(p) == row["path"] and p.is_relative_to(root), "contained native generated path")
    name = str(p.relative_to(root))
    need(name in raw and inventory[name] == {k: row[k] for k in ("bytes", "sha256")}, "generated bytes match whole inventory")
    need(type(row["identity"]) is list and len(row["identity"]) == 5
         and all(type(x) is int and x > 0 for x in row["identity"][:2])
         and row["identity"][2] == len(raw[name])
         and all(type(x) is int and x >= 0 for x in row["identity"][2:]),
         "observed native identity schema and authenticated generated size")
    # Copied Mac files have different inode/timestamps. These remain observed
    # native metadata, not an independent cross-filesystem inode proof.
    return raw[name]


def _retirement(closeout, dcl, inventory):
    need(type(closeout) is dict and set(closeout) == {"source", "declaration_sha256", "inventory_sha256", "service", "cgroup"}
         and closeout["source"] == dcl["source"] and closeout["declaration_sha256"] == sha256(old._canonical(dcl)).hexdigest()
         and closeout["inventory_sha256"] == sha256(old._canonical(inventory)).hexdigest(), "external closeout binds exact source/declaration/inventory")
    s, original = closeout["service"], dcl["service"]
    need(type(s) is dict and all(s.get(k) == v for k, v in probe.UNIT_CAPS.items())
         and s.get("Id") == original["Id"] and s.get("InvocationID") == original["InvocationID"]
         and s.get("MainPID") == "0" and s.get("ExecMainStatus") == "0" and s.get("Result") == "success"
         and s.get("ControlGroup") == ""
         and (s.get("ActiveState"), s.get("SubState")) in (("inactive", "dead"), ("active", "exited")),
         "same successful externally retired capped unit with no main process")
    c = closeout["cgroup"]
    need(type(c) is dict and set(c) == {"path", "absent", "observed_pids"}
         and c["path"] == original["ControlGroup"] and c["absent"] is True and c["observed_pids"] == [],
         "external owned cgroup no longer exists")


def receive(root, inventory, closeout, packet):
    raw = old.authenticate(root, inventory)  # all leaves/hash checks precede all decode
    transition.control_fields(packet)  # seal and complete historical digest before any interpretation
    need(set(("receipt.json", "declaration.json", "supervision.json", "telemetry.json", "child.log")) <= set(raw)
         and "failure.json" not in raw, "complete successful diagnostic envelope")
    receipt, dcl = _json(raw["receipt.json"], "receipt"), _json(raw["declaration.json"], "declaration")
    need(set(receipt) == {"protocol", "source", "declaration_sha256", "owner_pid", "child_pid", "native_root", "device", "modules", "arms", "flags"}
         and receipt["protocol"] == dcl.get("protocol") == probe.PROTOCOL and receipt["flags"] == dcl.get("flags") == stages.FLAGS,
         "closed new protocol with all qualification flags false")
    source = receipt["source"]
    need(type(source) is str and re.fullmatch(r"[0-9a-f]{40}", source)
         and dcl.get("source") == source and receipt["declaration_sha256"] == sha256(raw["declaration.json"]).hexdigest(),
         "same source and whole declaration hash")
    native_root = probe.ROOT / "artifacts/evaluations" / ("efc-transition-" + source[:12])
    need(receipt["native_root"] == dcl.get("native_root") == str(native_root)
         and type(receipt["owner_pid"]) is int and type(receipt["child_pid"]) is int
         and 0 < receipt["owner_pid"] != receipt["child_pid"] > 0 and receipt["owner_pid"] == dcl.get("owner_pid"),
         "same native output and distinct owner/child identities")
    device = receipt["device"]
    need(type(device) is dict and set(device) == {"alias", "arch", "context", "object_id", "gpu_uuid"}
         and device["alias"] == "cuda:0" and type(device["arch"]) is int and device["arch"] == 120
         and device["gpu_uuid"] == probe.shared.GPU
         and all(type(device[k]) is int and device[k] > 0 for k in ("context", "object_id")), "literal native device identity")
    old._check_runtime(dcl.get("runtime"))
    need(dcl.get("bounds") == probe.BOUNDS and dcl.get("replay_input") == probe.retained.INPUT
         and dcl.get("control") == transition.control_manifest(packet) and dcl.get("exclusive_gpu_claimed") is False,
         "unchanged bounds/domain input/control/shared lane")
    service = dcl["service"]
    need(service.get("name") == service.get("Id") == probe.unit(source)
         and service.get("MainPID") == str(receipt["owner_pid"]) and service.get("ActiveState") == "active"
         and all(service.get(k) == v for k, v in probe.UNIT_CAPS.items())
         and service.get("ControlGroup") == probe.retained.CGROUP_PARENT + probe.unit(source), "declared capped owner unit")
    src = dcl.get("source_binding")
    need(type(src) is dict and set(src) == {"source", "branch", "tree", "leaves"}
         and src["source"] == source and src["branch"] == probe.BRANCH
         and type(src["tree"]) is str and re.fullmatch(r"[0-9a-f]{40}", src["tree"])
         and type(src["leaves"]) is list and src["leaves"], "closed committed source inventory declaration")
    seen = set()
    for leaf in src["leaves"]:
        need(type(leaf) is dict and set(leaf) == {"path", "bytes", "git_blob", "sha256"}
             and type(leaf["path"]) is str and leaf["path"] not in ("", ".") and "\\" not in leaf["path"]
             and all(ord(c) >= 32 for c in leaf["path"])
             and not Path(leaf["path"]).is_absolute() and ".." not in Path(leaf["path"]).parts
             and str(Path(leaf["path"])) == leaf["path"] and leaf["path"] not in seen
             and type(leaf["bytes"]) is int and leaf["bytes"] >= 0
             and type(leaf["git_blob"]) is str and re.fullmatch(r"[0-9a-f]{40}", leaf["git_blob"])
             and type(leaf["sha256"]) is str and re.fullmatch(r"[0-9a-f]{64}", leaf["sha256"]),
             "unique canonical source leaf schema and whole digest declarations")
        seen.add(leaf["path"])
    need(probe.OWN <= seen, "source inventory includes all four reviewed paths")
    old._check_supervision(raw, receipt)
    _retirement(closeout, dcl, inventory)
    telemetry = _json(raw["telemetry.json"], "telemetry")
    need(telemetry.get("flags") == stages.FLAGS and type(telemetry.get("samples")) is list
         and 0 < len(telemetry["samples"]) <= 1024, "bounded retained shared telemetry")
    for sample in [dcl["baseline"], *telemetry["samples"]]:
        probe.shared.capacity(sample, dcl["baseline"])
    modules = receipt["modules"]
    need(type(modules) is dict and set(modules) == set(executable.GROUPS), "three exact compiled module records")
    observed = {}
    for role, names in executable.GROUPS.items():
        m = modules[role]
        need(type(m) is dict and set(m) == {"protocol", "role", "generated", "module_hash", "offline_disassembly", "explicit_load", "bindings", "flags",
            "loaded_binary_bytes_observed", "driver_jit_machine_code_observed", "actual_dispatch_observed"}
            and m["protocol"] == executable.PROTOCOL and m["role"] == role and m["flags"] == stages.FLAGS
            and all(m[k] is False for k in ("loaded_binary_bytes_observed", "driver_jit_machine_code_observed", "actual_dispatch_observed")),
            "closed observed executable record without driver claims")
        need(set(m["generated"]) == {"binary", "metadata", "source"}
             and set(m["offline_disassembly"]) == set(m["bindings"]) == set(names), "closed role artifact/entry sets")
        content = {n: _artifact(raw, inventory, row, native_root) for n, row in m["generated"].items()}
        need(all(Path(row["path"]).parent == native_root / ("compiled-" + role) for row in m["generated"].values()), "same role directories")
        load = m["explicit_load"]
        need(load.get("binary_path") == m["generated"]["binary"]["path"]
             and load.get("metadata_path") == m["generated"]["metadata"]["path"]
             and load.get("output_arch") == 120 and load.get("block_dim") == 256
             and load.get("returned_executable_is_cache_entry") is True
             and load.get("device_object_id") == device["object_id"], "exact observed explicit loader paths/context")
        meta = old._json(content["metadata"], "metadata")
        for n in names:
            b = m["bindings"][n]
            need(b.get("artifact_format") == "cubin" and b.get("binary_path") == load["binary_path"]
                 and b.get("metadata_path") == load["metadata_path"]
                 and b.get("binary_sha256") == sha256(content["binary"]).hexdigest()
                 and b.get("metadata_sha256") == sha256(content["metadata"]).hexdigest()
                 and b.get("module_hash") == m["module_hash"] and b.get("context") == device["context"]
                 and b.get("device") == device["alias"] and b.get("device_arch") == 120 and b.get("block_dim") == 256
                 and b.get("observed_object_ids", {}).get("module") == load.get("module_object_id")
                 and b.get("observed_object_ids", {}).get("executable") == load.get("executable_object_id")
                 and b.get("observed_object_ids", {}).get("device") == device["object_id"]
                 and type(b.get("forward_handle")) is int and b["forward_handle"] > 0
                 and type(b.get("module_handle")) is int and b["module_handle"] > 0
                 and meta.get(b["symbol"] + "_smem_bytes") == b.get("forward_smem_bytes"), "same observed entry-point byte/module bindings")
            need(n + ".sass" in raw and raw.get(n + ".stderr") == b"", "retained joined tool output")
            checked = binary.verify_disassembly(content["binary"], raw[n + ".sass"], n, b["symbol"])
            need(checked == m["offline_disassembly"][n], "independently reproduced exact offline function span")
            observed[n] = b
    need(len({modules[r]["explicit_load"]["module_object_id"] for r in modules}) == 3, "three distinct actual modules")
    arms, anchors, packets = receipt["arms"], {}, {}
    need(type(arms) is dict and set(arms) == {"reference", "control"}, "two exact caller arms")
    need(type(packet) is scratch.DecodedPacket and packet._sealed is True, "external authenticated historical packet")
    for arm in arms:
        need(type(arms[arm]) is dict and set(arms[arm]) == {"observer", "scratch", "staging"}, "closed arm restoration and observation")
        need(arms[arm]["scratch"] == dict(protocol=scratch.PROTOCOL,
            decision="dense-solver-scratch-restored-no-dispatch-or-qualification",
            source_sha256=packet.sha256, source_bytes=len(packet.raw), restored_fields=list(scratch.RESTORE_ORDER),
            retained_source_bytes=True, solver_called=False, forward_called=False, flags=dict(scratch.FLAGS)),
            "same complete authenticated original restoration in both arms")
        staging = arms[arm]["staging"]
        if arm == "reference":
            need(staging is None, "no control staging in reference arm")
        else:
            need(staging == dict(protocol=transition.CONTROL_PROTOCOL,
                overrides=transition.control_manifest(packet)["overrides"],
                fields=list(transition.control_fields(packet)), preflight_complete=True,
                same_stream_copy=True, gpu_numpy_readback=False, timing_changed_by_staging=True,
                qualification=dict(stages.FLAGS)), "exact thirteen-field typed staging receipt")
        o = arms[arm]["observer"]
        need(o.get("protocol") == dispatch.PROTOCOL and o.get("base") == dispatch.BASE
             and o.get("caller") == "_update_constraint" and o.get("track_changes") is False
             and o.get("observed_stages") == list(stages.STAGES) and o.get("call_site_lines") == [2156, 2180, 2197, 2214]
             and o.get("call_sites_observed") is True and o.get("timing_changed_by_readback") is True
             and o.get("bindings") == observed and o.get("qualification") == stages.FLAGS
             and all(o.get(k) is False for k in ("explicit_load_provenance_authenticated", "native_gpu_execution_authenticated",
                 "capture_origin_authenticated", "external_unit_retirement_authenticated")), "same complete observed four-stage caller graph")
        c = o["capture"]
        need(c.get("protocol") == stages.PROTOCOL and c.get("stages") == list(stages.STAGES)
             and c.get("timing_changed_by_readback") is True and c.get("qualification") == stages.FLAGS
             and set(c["packets"]) == set(stages.PHASES), "complete caller capture anchors")
        packets[arm], anchors[arm] = {}, {}
        for phase in stages.PHASES:
            name = arm + "-" + phase + ".bin"
            need(name in raw and c["packets"][phase] == inventory[name], "whole raw packet matches observed boundary anchor")
            packets[arm][phase], anchors[arm][phase] = raw[name], inventory[name]
    result = receive_banks(packets, anchors, packet)
    return dict(protocol=PROTOCOL, source=source, decision="positive-efc-native-diagnostic-received-not-qualification",
                artifact_files=len(inventory), artifact_bytes=sum(v["bytes"] for v in inventory.values()),
                inventory_sha256=sha256(old._canonical(inventory)).hexdigest(), banks=result,
                external_retirement_evidence_checked=True, timing_changed_by_readback=True,
                driver_loaded_bytes_observed=False, runtime_cause_proven=False, qualification=dict(stages.FLAGS))


def receive_banks(arms, anchors, packet):
    """Authenticate all sixteen whole banks, then check each arm independently.

    Synthetic input can satisfy this contract; outer native origin and retirement
    remain external. No cross-arm force/state/dense equality is imposed.
    """
    need(type(arms) is dict and type(anchors) is dict
         and set(arms) == set(anchors) == {"reference", "control"}, "closed two-arm transition envelope")
    for arm in ("reference", "control"):
        need(type(arms[arm]) is dict and type(anchors[arm]) is dict
             and set(arms[arm]) == set(anchors[arm]) == set(stages.PHASES),
             "closed eight-bank arm")
        for phase in stages.PHASES:
            raw, a = arms[arm][phase], anchors[arm][phase]
            need(type(raw) is bytes and len(raw) == stages.PACKET_BYTES
                 and type(a) is dict and set(a) == {"bytes", "sha256"}
                 and type(a["bytes"]) is int and a["bytes"] == len(raw)
                 and type(a["sha256"]) is str and a["sha256"] == sha256(raw).hexdigest(),
                 "whole sixteen-bank anchors before decode")
    transition.control_fields(packet)  # seal before fields access
    reference = stages.pack_bank({n: packet.fields[n] for n in stages.ORDER})
    need(arms["reference"]["init_cost.before"] == reference, "exact historical reference initial bank")
    ref_stages = stages.analyze_arm(arms["reference"], arm="reference")
    ref_efc = transition.analyze(*(stages.unpack_bank(arms["reference"][phase])
                                  for phase in ("efc.before", "efc.after")))
    need(not any(ref_efc[k] for k in ("force_mismatches", "state_mismatches", "cost_outside_interval")),
         "reference EFC row-model consistency")
    control = transition.receive_control(arms["control"], anchors["control"], packet)
    return dict(protocol=PROTOCOL, decision="positive-transition-two-arm-packet-contract-only",
                packet_bytes=stages.PACKET_BYTES, total_bytes=16 * stages.PACKET_BYTES,
                reference=dict(stages=ref_stages, efc=ref_efc), control=control,
                cross_arm_output_equality_required=False, capture_origin_authenticated=False,
                native_execution_authenticated=False, qualification=dict(stages.FLAGS))
